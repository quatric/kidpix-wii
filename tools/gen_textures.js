// Generates src/textures_data.c from the jskidpix texture definitions.
// usage: node tools/gen_textures.js ref/kidpix/js/textures/textures.js > src/textures_data.c
const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8');
function mkCanvas() {
  const c = { width: 0, height: 0, px: null };
  c.getContext = () => {
    if (!c.px) c.px = new Uint8Array(c.width * c.height);
    let rects = [], stroked = false;
    const ctx = {
      beginPath() { rects = []; }, closePath() {},
      rect(x, y, w, h) { rects.push([x, y, w, h]); },
      fillRect(x, y, w, h) { fillR(x, y, w, h); },
      fill() { for (const r of rects) fillR(...r); rects = []; },
      stroke() { stroked = true; // 1px outline of the rect (aliased approximation)
        for (const [x, y, w, h] of rects) {
          fillR(0, 0, c.width, 1); fillR(0, 0, 1, c.height);
        } },
      set fillStyle(v) {}, set strokeStyle(v) {},
    };
    function fillR(x, y, w, h) {
      for (let j = Math.floor(y); j < Math.min(c.height, y + h); j++)
        for (let i = Math.floor(x); i < Math.min(c.width, x + w); i++)
          if (i >= 0 && j >= 0) c.px[j * c.width + i] = 1;
    }
    return ctx;
  };
  return c;
}
const document = { createElement: () => mkCanvas() };
const KiddoPaint = { Current: { modifiedAlt: false }, Colors: {}, Textures: {}, Display: {
  context: { createPattern: (c) => c } } };
eval(src.replace(/^KiddoPaint\.Textures\./gm, 'KiddoPaint.Textures.'));
const T = KiddoPaint.Textures;
const names = ['Solid','Partial1','Partial2','Partial3','PartialArtifactAlias','Speckles','Stripes','Thatch',
  'Shingles','Bubbles','Diamond','Ribbon','Sand','Brick','Chevron','Stairs','Cross','DiagBrick','CornerStair','Houndstooth'];
let out = '// generated by tools/gen_textures.js - do not edit\n#include "kidpix.h"\n\n';
let tab = 'const KpTexture kp_textures[KP_TEXTURE_COUNT] = {\n';
tab += '    { 0, 0, 0 }, /* None */\n';
for (const n of names) {
  const c = T[n]('black');
  if (!c || !c.px) throw new Error(n);
  const w = c.width, h = c.height;
  out += `static const unsigned char tex_${n}[] = {${Array.from(c.px).join(',')}};\n`;
  tab += `    { ${w}, ${h}, tex_${n} },\n`;
}
tab += '};\n';
console.log(out + '\n' + tab);
