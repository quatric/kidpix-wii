// usage: node tools/gen_palettes.js ref/kidpix/js/util/colors.js > src/palettes_data.c
const fs = require('fs');
const src = fs.readFileSync(process.argv[2], 'utf8').split('\n').filter(l => !/^function|^\s+var |getColorIndices/.test(l)).join('\n');
const KiddoPaint = { Colors: {} , Display: {}};
// only evaluate up to the first function that needs DOM: palettes + .All
const cut = src.indexOf('KiddoPaint.Colors.Current.PaletteNumber');
eval(src.slice(0, cut));
const A = KiddoPaint.Colors.All;
function parse(c) {
  c = c.trim();
  let m = c.match(/^#([0-9a-f]{6})$/i);
  if (m) { const v = parseInt(m[1], 16); return [v >> 16, (v >> 8) & 255, v & 255]; }
  m = c.match(/rgb\(\s*(\d+)\s*,\s*(\d+)\s*,\s*(\d+)\s*\)/);
  if (m) return [+m[1], +m[2], +m[3]];
  throw new Error(c);
}
let out = '// generated by tools/gen_palettes.js - do not edit\n#include "kidpix.h"\n\nconst u32 kp_palettes[KP_PALETTE_COUNT][32] = {\n';
for (const p of A) {
  if (p.length !== 32) throw new Error('palette len ' + p.length);
  out += '    {' + p.map(c => { const [r, g, b] = parse(c); return '0x' + (((r << 24) | (g << 16) | (b << 8) | 255) >>> 0).toString(16).padStart(8, '0'); }).join(',') + '},\n';
}
out += '};\n';
console.log(out);
