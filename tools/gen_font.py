#!/usr/bin/env python3
"""Render an ASCII alpha atlas with Pillow's bundled font -> src/font_data.c"""
import sys
from PIL import Image, ImageDraw, ImageFont
SIZES = [("ui", 13), ("big", 40)]
out = ['// generated by tools/gen_font.py - do not edit', '#include "kidpix.h"', '']
tabs = []
for name, px in SIZES:
    font = ImageFont.load_default(size=px)
    asc, desc = font.getmetrics()
    h = asc + desc
    entries = []
    blob = bytearray()
    for c in range(32, 127):
        ch = chr(c)
        adv = int(round(font.getlength(ch)))
        im = Image.new("L", (max(adv, 1) + 4, h), 0)
        ImageDraw.Draw(im).text((1, 0), ch, font=font, fill=255)
        bbox = im.getbbox()
        if bbox is None:
            entries.append((0, 0, 0, 0, adv, len(blob))); continue
        x0, y0, x1, y1 = bbox
        crop = im.crop(bbox)
        off = len(blob)
        blob += crop.tobytes()
        entries.append((x1 - x0, y1 - y0, x0 - 1, y0, adv, off))
    out.append(f"static const unsigned char font_{name}_px[] = {{{','.join(map(str, blob))}}};")
    out.append(f"static const KpGlyph font_{name}_g[95] = {{")
    for e in entries:
        out.append("    {%d,%d,%d,%d,%d,%d}," % e)
    out.append("};")
    tabs.append((name, h, asc))
out.append("const KpFont kp_fonts[2] = {")
for name, h, asc in tabs:
    out.append(f"    {{ {h}, {asc}, font_{name}_g, font_{name}_px }},")
out.append("};")
open(sys.argv[1], "w").write("\n".join(out) + "\n")
